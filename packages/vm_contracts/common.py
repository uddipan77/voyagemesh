"""Shared vocabulary used by every other contract module.

Two types here carry most of the project's weight:

* :class:`Money` — an amount is *never* a bare float. Pairing the value with its currency
  at the type level is what makes the "every price includes a currency" output guardrail
  a tautology rather than a runtime check that can be forgotten.
* :class:`Provenance` — every fact that reaches the user carries where it came from, how
  it was obtained, and when. This is what allows the UI to label data `LIVE` / `CACHED` /
  `MOCKED` / `FIXTURE` honestly instead of presenting everything with equal confidence.
"""

from __future__ import annotations

from datetime import UTC, datetime
from decimal import ROUND_HALF_UP, Decimal
from enum import StrEnum
from typing import Annotated, Self

from pydantic import BaseModel, ConfigDict, Field, computed_field, field_validator, model_validator

__all__ = [
    "AccessibilityNeed",
    "AccommodationType",
    "ConfidenceLevel",
    "Currency",
    "DataOrigin",
    "GeoPoint",
    "Money",
    "Provenance",
    "RankingStrategy",
    "TransportMode",
    "utc_now",
]


def utc_now() -> datetime:
    """Timezone-aware current UTC time.

    Used everywhere instead of ``datetime.now()``: naive timestamps compared across
    service boundaries are a reliable source of off-by-hours bugs.
    """
    return datetime.now(UTC)


class StrictModel(BaseModel):
    """Base for all contract models.

    ``extra="forbid"`` is deliberate and load-bearing: an *unexpected* field in an A2A
    artifact or a provider payload is a contract violation we want to hear about loudly,
    not silently discard.

    But a model's own **computed** fields are not unexpected — ``model_dump()`` emits them,
    and re-parsing a dumped model (the exact round-trip an agent→orchestrator handoff
    performs) would otherwise fail on them. The before-validator below drops a model's own
    computed-field names from incoming data, so feeding a model its own output is a no-op
    while a genuinely unknown field still raises. Nesting is handled for free: each nested
    ``StrictModel`` strips its own computed fields as pydantic validates it.
    """

    model_config = ConfigDict(
        extra="forbid",
        frozen=True,
        str_strip_whitespace=True,
        validate_assignment=True,
        use_enum_values=False,
    )

    @model_validator(mode="before")
    @classmethod
    def _drop_own_computed_fields(cls, data: object) -> object:
        computed = cls.model_computed_fields
        if not computed or not isinstance(data, dict):
            return data
        overlap = computed.keys() & data.keys()
        if not overlap:
            return data
        return {key: value for key, value in data.items() if key not in overlap}


