# Money
# ---------------------------------------------------------------------------
class Money(StrictModel):
    """A monetary amount bound to its currency.

    Amounts use :class:`~decimal.Decimal`, not ``float``. Summing 0.1 + 0.2 in binary
    floating point and comparing the result against a budget is exactly the kind of
    quiet error this project exists to avoid.
    """

    amount: Annotated[Decimal, Field(ge=0, max_digits=12, decimal_places=2)]
    currency: Currency

    @field_validator("amount", mode="before")
    @classmethod
    def _quantize(cls, value: object) -> object:
        """Round to cents *before* the 2-dp constraint is applied.

        Two reasons this must run first. Providers legitimately return sub-cent precision
        (a per-night rate of 33.333), and rejecting those outright would be wrong — cents
        are the correct resolution for money. And normalising here makes equality and
        hashing behave: without it Decimal("10.5") != Decimal("10.50") despite being the
        same amount. The ``decimal_places=2`` constraint then acts as a post-condition.
        """
        if isinstance(value, Decimal):
            return value.quantize(Decimal("0.01"), ROUND_HALF_UP)
        if isinstance(value, int | str):
            try:
                return Decimal(value).quantize(Decimal("0.01"), ROUND_HALF_UP)
            except (ArithmeticError, ValueError):
                return value  # let pydantic produce the proper validation error
        return value

    @classmethod
    def zero(cls, currency: Currency) -> Money:
        return cls(amount=Decimal("0.00"), currency=currency)

    @classmethod
    def of(cls, amount: Decimal | int | str, currency: Currency) -> Money:
        """Construct from a plain value. Never accepts ``float`` — see class docstring."""
        return cls(amount=Decimal(str(amount)), currency=currency)

    def _require_same_currency(self, other: Money, op: str) -> None:
        if self.currency is not other.currency:
            raise ValueError(
                f"cannot {op} {self.currency.value} and {other.currency.value}: convert to a "
                f"single currency before combining amounts"
            )

    def __add__(self, other: Money) -> Money:
        self._require_same_currency(other, "add")
        return Money(amount=self.amount + other.amount, currency=self.currency)

    def __sub__(self, other: Money) -> Money:
        """Subtract. May produce a negative result, which callers must handle.

        Note the ``ge=0`` field constraint: an over-budget difference is expressed as
        :class:`~vm_contracts.budget.BudgetSummary.overspend`, a separate non-negative
        amount, rather than as negative money.
        """
        self._require_same_currency(other, "subtract")
        result = self.amount - other.amount
        if result < 0:
            raise ValueError(
                f"subtraction would yield a negative amount "
                f"({self.amount} - {other.amount}); use difference_or_zero() and inspect "
                f"exceeds() to express an overspend"
            )
        return Money(amount=result, currency=self.currency)

    def difference_or_zero(self, other: Money) -> Money:
        """``self - other``, floored at zero. Safe for 'remaining budget' calculations."""
        self._require_same_currency(other, "subtract")
        return Money(
            amount=max(Decimal("0.00"), self.amount - other.amount), currency=self.currency
        )

    def times(self, factor: int) -> Money:
        """Multiply by a whole number — nights, travellers, seats."""
        if factor < 0:
            raise ValueError("factor must be non-negative")
        return Money(amount=self.amount * factor, currency=self.currency)

    def exceeds(self, limit: Money) -> bool:
        self._require_same_currency(limit, "compare")
        return self.amount > limit.amount

    def __lt__(self, other: Money) -> bool:
        self._require_same_currency(other, "compare")
        return self.amount < other.amount

    def __le__(self, other: Money) -> bool:
        self._require_same_currency(other, "compare")
        return self.amount <= other.amount

    def __str__(self) -> str:
        return f"{self.amount:.2f} {self.currency.value}"


