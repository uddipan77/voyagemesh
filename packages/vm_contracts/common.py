class AccessibilityNeed(StrEnum):
    """Accessibility requirements. These are *hard* constraints, never trade-offs.

    An option that fails an accessibility requirement is filtered out entirely rather than
    scored lower — ranking a step-free requirement against price would be wrong.
    """

    STEP_FREE_ACCESS = "step_free_access"
    WHEELCHAIR_ACCESSIBLE = "wheelchair_accessible"
    ELEVATOR_REQUIRED = "elevator_required"
    ACCESSIBLE_BATHROOM = "accessible_bathroom"
    LOW_WALKING_DISTANCE = "low_walking_distance"
    HEARING_ASSISTANCE = "hearing_assistance"
    VISUAL_ASSISTANCE = "visual_assistance"
    SERVICE_ANIMAL_FRIENDLY = "service_animal_friendly"


class ConfidenceLevel(StrEnum):
    """Overall trustworthiness of a result section."""

    HIGH = "high"
    """Live or curated data, complete, all constraints verified."""

    MEDIUM = "medium"
    """Mocked or partially cached data, or minor gaps."""

    LOW = "low"
    """Significant degradation — a dependency failed or constraints were relaxed."""

    NONE = "none"
    """No usable data for this section."""


