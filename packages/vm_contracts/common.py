class Currency(StrEnum):
    """ISO-4217 codes supported by the planner."""

    EUR = "EUR"
    GBP = "GBP"
    USD = "USD"
    CHF = "CHF"
    CZK = "CZK"
    PLN = "PLN"
    SEK = "SEK"
    DKK = "DKK"
    NOK = "NOK"


class DataOrigin(StrEnum):
    """How a piece of data was obtained. Rendered as a badge in the UI.

    The distinction between ``MOCKED`` and ``FIXTURE`` matters: fixtures are curated real
    facts (a museum's real address), whereas mocked records are *generated* and correspond
    to no real-world offer. Conflating them would understate how synthetic the transport
    and accommodation results are.
    """

    LIVE = "live"
    """Fetched from an external API during this request."""

    CACHED = "cached"
    """Served from Redis; originally live. ``retrieved_at`` is the original fetch time."""

    MOCKED = "mocked"
    """Generated by a deterministic mock provider. Corresponds to no real offer."""

    FIXTURE = "fixture"
    """Curated real-world reference data stored in the repository."""

    COMPUTED = "computed"
    """Derived by VoyageMesh's own deterministic code (budgets, scores, distances)."""

    UNAVAILABLE = "unavailable"
    """The source could not be reached. No data — never a fabricated substitute."""


