# Provenance
# ---------------------------------------------------------------------------
class Provenance(StrictModel):
    """Where a piece of data came from, and when.

    Attached to every offer, attraction, and forecast. The output guardrail rejects any
    record whose provenance claims :attr:`DataOrigin.LIVE` without a ``retrieved_at``
    timestamp, and the UI refuses to render an unlabelled record at all.
    """

    origin: DataOrigin
    source_name: Annotated[str, Field(min_length=1, max_length=120)]
    """Human-readable source, e.g. ``"Open-Meteo"`` or ``"VoyageMesh mock rail provider"``."""

    source_id: Annotated[str | None, Field(max_length=200)] = None
    """Stable identifier of the record within the source, used to prove an offer that
    reaches the user actually came from a provider result."""

    retrieved_at: datetime | None = None
    source_url: Annotated[str | None, Field(max_length=500)] = None
    license_note: Annotated[str | None, Field(max_length=200)] = None
    cache_age_seconds: Annotated[int | None, Field(ge=0)] = None

    @model_validator(mode="after")
    def _validate_origin_requirements(self) -> Self:
        if self.origin in (DataOrigin.LIVE, DataOrigin.CACHED) and self.retrieved_at is None:
            raise ValueError(
                f"provenance with origin={self.origin.value} must carry retrieved_at; "
                f"data claimed to come from a real source must say when it was fetched"
            )
        if self.retrieved_at is not None and self.retrieved_at.tzinfo is None:
            raise ValueError("retrieved_at must be timezone-aware (use vm_contracts.utc_now)")
        if self.origin is DataOrigin.CACHED and self.cache_age_seconds is None:
            raise ValueError("cached data must report cache_age_seconds so staleness is visible")
        return self

    @computed_field  # type: ignore[prop-decorator]
    @property
    def is_synthetic(self) -> bool:
        """True when this record corresponds to no real-world offer."""
        return self.origin is DataOrigin.MOCKED

    @computed_field  # type: ignore[prop-decorator]
    @property
    def display_label(self) -> str:
        """Uppercase badge text for the UI."""
        return self.origin.value.upper()

    @classmethod
    def live(
        cls,
        source_name: str,
        *,
        source_id: str | None = None,
        source_url: str | None = None,
        license_note: str | None = None,
    ) -> Provenance:
        return cls(
            origin=DataOrigin.LIVE,
            source_name=source_name,
            source_id=source_id,
            retrieved_at=utc_now(),
            source_url=source_url,
            license_note=license_note,
        )

    @classmethod
    def mocked(cls, source_name: str, *, source_id: str | None = None) -> Provenance:
        return cls(
            origin=DataOrigin.MOCKED,
            source_name=source_name,
            source_id=source_id,
            retrieved_at=utc_now(),
        )

    @classmethod
    def fixture(cls, source_name: str, *, source_id: str | None = None) -> Provenance:
        return cls(origin=DataOrigin.FIXTURE, source_name=source_name, source_id=source_id)

    @classmethod
    def computed(cls, source_name: str = "VoyageMesh deterministic calculation") -> Provenance:
        return cls(origin=DataOrigin.COMPUTED, source_name=source_name)

    @classmethod
    def unavailable(cls, source_name: str) -> Provenance:
        return cls(origin=DataOrigin.UNAVAILABLE, source_name=source_name)

    def as_cached(self, *, age_seconds: int) -> Provenance:
        """Return a copy re-labelled as cache-served, preserving the original fetch time."""
        return self.model_copy(
            update={"origin": DataOrigin.CACHED, "cache_age_seconds": age_seconds}
        )
