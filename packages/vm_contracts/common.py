# Geography
# ---------------------------------------------------------------------------
class GeoPoint(StrictModel):
    """A WGS-84 coordinate."""

    latitude: Annotated[float, Field(ge=-90.0, le=90.0)]
    longitude: Annotated[float, Field(ge=-180.0, le=180.0)]

    def __str__(self) -> str:
        return f"({self.latitude:.5f}, {self.longitude:.5f})"


